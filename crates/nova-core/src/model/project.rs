        let title_id = title_object.id;
        title.frames[0].keyframe = true;
        title.frames[0].label = Some("intro".into());
        title.frames[0].objects.push(title_object.clone());
        title.frames[0].tween = Some(Tween::default());
        title.frames[24].keyframe = true;

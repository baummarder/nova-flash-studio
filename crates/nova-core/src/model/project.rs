pub type ProjectId = Uuid;

/// On-disk project format tag. Changing the document layout requires bumping
/// [`CURRENT_FORMAT_VERSION`] and adding a migration step.
pub const FORMAT_TAG: &str = "nova-flash-studio";
pub const CURRENT_FORMAT_VERSION: u32 = 1;

fn now_unix() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0)
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Metadata {
    pub name: String,
    #[serde(default)]
    pub author: String,
    #[serde(default)]
    pub description: String,
    #[serde(default = "now_unix")]
    pub created_unix: u64,
    #[serde(default = "now_unix")]
    pub modified_unix: u64,
}

impl Metadata {
    pub fn new(name: impl Into<String>) -> Self {
        let now = now_unix();
        Self {
            name: name.into(),
            author: String::new(),
            description: String::new(),
            created_unix: now,
            modified_unix: now,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum TargetRuntime {
    /// AVM2 / ActionScript 3 (long-term primary target).
    #[default]
    Avm2,
    /// Legacy AVM1 bytecode (not generated by this milestone).
    Avm1,
}

impl TargetRuntime {
    pub fn label(self) -> &'static str {
        match self {
            Self::Avm2 => "AVM2 (ActionScript 3)",
            Self::Avm1 => "AVM1 (Legacy)",
        }
    }
}


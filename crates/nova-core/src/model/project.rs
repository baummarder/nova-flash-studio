pub enum SwfCompression {
    None,
    #[default]
    Zlib,
}

/// Where the source of a script came from. This is deliberately part of the
/// project model so the editor, the CLI and any analysis tool can distinguish
/// original source from reconstructed or compiled code.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum CodeProvenance {
    /// Authored in NØVA or read verbatim from an authoring file.
    #[default]
    OriginalSource,
    /// Recovered by a decompiler. Never presented as original.
    Decompiled,
    /// Rebuilt from bytecode or an incomplete source container.
    Reconstructed,
    /// Written by an importer/exporter or a template.
    Generated,
    /// Only AVM2 ABC bytes were available; no source was recovered.
    CompiledBytecode,
}

impl CodeProvenance {
    pub fn label(self) -> &'static str {
        match self {
            Self::OriginalSource => "Originalquelle",
            Self::Decompiled => "Dekompiliert",
            Self::Reconstructed => "Rekonstruiert",
            Self::Generated => "Generiert",
            Self::CompiledBytecode => "Kompiliertes ABC (kein Quelltext)",
        }
    }

    pub fn is_original(self) -> bool {
        matches!(self, Self::OriginalSource)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum SourceFormat {
    #[default]
    Nova,
    Fla,
    Swf,
}

impl SourceFormat {
    pub fn label(self) -> &'static str {
        match self {
            Self::Nova => "NØVA",
            Self::Fla => "Adobe FLA/XFL",
            Self::Swf => "SWF",
        }
    }
}

/// One preserved SWF `SymbolClass` entry. Character ids refer to the imported
/// SWF and are matched against [`ObjectInstance::source_character`] when the
/// project is exported again.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SymbolClassLink {
    pub character_id: u16,
    pub class_name: String,
}

/// Source information kept in an imported project. It is optional so existing
/// `.nova` files remain valid, and it lets the editor and analysis tools warn
/// about lossy conversions without guessing from the file extension.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SourceInfo {
    pub format: SourceFormat,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub original_path: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub original_version: Option<String>,
    #[serde(default)]
    pub note: String,
    /// Preserved SWF class links. Empty for native and FLA projects.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub symbol_classes: Vec<SymbolClassLink>,
}

impl SourceInfo {
    pub fn new(format: SourceFormat) -> Self {
        Self {
            format,
            original_path: None,
            original_version: None,
            note: String::new(),
            symbol_classes: Vec::new(),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ExportConfig {
    pub target: TargetRuntime,
    /// SWF version. 10 is the safe baseline for AVM2 content; 9 is the first
    /// AVM2-capable version.
    pub swf_version: u8,
    pub compression: SwfCompression,
    /// Reserved for the ActionScript compiler milestone. The exporter warns
    /// when this is set but no bytecode exists.
    #[serde(default)]
    pub include_scripts: bool,
}

impl Default for ExportConfig {
    fn default() -> Self {
        Self {
            target: TargetRuntime::Avm2,
            swf_version: 10,
            compression: SwfCompression::Zlib,
            include_scripts: true,
        }
    }
}


    pub fn touch(&mut self) {
        self.metadata.modified_unix = now_unix();
    }

    pub fn active_scene_index(&self) -> usize {
        self.active_scene
            .and_then(|id| self.scenes.iter().position(|s| s.id == id))
            .unwrap_or(0)
    }

    pub fn active_scene(&self) -> Option<&Scene> {
        self.scenes.get(self.active_scene_index())
    }

    pub fn active_scene_mut(&mut self) -> Option<&mut Scene> {
        let index = self.active_scene_index();
        self.scenes.get_mut(index)
    }

    pub fn add_scene(&mut self, name: impl Into<String>) -> Uuid {
        let template = self.active_scene();
        let width = template.map(|scene| scene.width).unwrap_or(550.0);
        let height = template.map(|scene| scene.height).unwrap_or(400.0);
        let background = template
            .map(|scene| scene.background)
            .unwrap_or(Rgba::rgb(18, 20, 26));
        let fps = template.map(|scene| scene.fps).unwrap_or(24.0);
        let mut scene = Scene::new(name, width, height);
        scene.background = background;
        scene.fps = fps;
        let id = scene.id;
        self.scenes.push(scene);
        self.active_scene = Some(id);
        self.touch();
        id
    }

    pub fn add_layer(&mut self, name: impl Into<String>, frame_count: usize) -> Option<Uuid> {
        let layer = Layer::new(name, frame_count);
        let id = layer.id;
        self.active_scene_mut()?.layers.push(layer);
        self.touch();
        Some(id)
    }


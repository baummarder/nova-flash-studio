#!/usr/bin/env python3
"""Generate legal/THIRD-PARTY-NOTICES.md from `cargo metadata`.

Lists every non-path (registry) dependency of the workspace with its declared
SPDX license expression. SPDX license texts referenced by the inventory are
checked in under LICENSES/ and shipped in the release bundle.

Run from the repository root:  python scripts/gen-third-party-notices.py
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "legal" / "THIRD-PARTY-NOTICES.md"
LICENSES = ROOT / "LICENSES"

HEADER = """# Third-Party Notices

NØVA Flash Studio is licensed under the MIT OR Apache-2.0 licenses; see
`LICENSE-MIT.txt` and `LICENSE-APACHE-2.0.txt` in this directory.

The application bundles or links the third-party Rust crates listed below.
License expressions are reproduced from each crate's `Cargo.toml` metadata as
reported by `cargo metadata`. Where a license identifier matches a standard
SPDX text, that text is included in the `LICENSES/` directory of this
repository and in the release bundle's `licenses/` folder.

This file is generated by `scripts/gen-third-party-notices.py`. Regenerate it
after dependency changes with:

```bash
python scripts/gen-third-party-notices.py
```

| Crate | Version | License expression |
| --- | --- | --- |
"""

FOOTER = """
## License texts

The following SPDX license texts are shipped under `licenses/` in the release
bundle (sources in `LICENSES/`):

"""


def spdx_ids(expression: str) -> list[str]:
    """Extract plausible SPDX identifiers from a license expression."""
    ids = re.findall(r"[A-Za-z0-9][A-Za-z0-9.+-]*(?:\s+OR\s+|\s+AND\s+|\s+WITH\s+)?", expression)
    # Simpler: split on operators and keep tokens that look like SPDX ids.
    tokens = re.split(r"\s+(?:OR|AND|WITH)\s+|[()\[\],]", expression)
    return sorted({t.strip() for t in tokens if t.strip()})


def main() -> None:
    metadata = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1"],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )

    rows = []
    used_ids: set[str] = set()
    for package in sorted(metadata["packages"], key=lambda p: p["name"].lower()):
        if package.get("source") is None:
            continue  # workspace/path crates are our own code
        license_expr = (package.get("license") or "").strip() or "(not declared)"
        rows.append(f"| `{package['name']}` | {package['version']} | {license_expr} |")
        for identifier in spdx_ids(license_expr):
            if (LICENSES / f"{identifier}.txt").is_file():
                used_ids.add(identifier)

    lines = [HEADER.rstrip("\n"), *rows, FOOTER.rstrip("\n")]
    for identifier in sorted(used_ids):
        lines.append(f"- `{identifier}` — `licenses/{identifier}.txt`\n")

    if not used_ids:
        lines.append("- No matching SPDX texts were found in `LICENSES/`.\n")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} third-party crates, {len(used_ids)} license texts")


if __name__ == "__main__":
    try:
        main()
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        raise SystemExit(1)
